import { test, expect } from '@playwright/test';
import { login, unique } from './helpers';
test('owner creates client, project, task and updates Kanban status', async ({ page }) => {
  const id = unique(); const clientName = `E2E Client ${id}`; const projectName = `E2E Project ${id}`; const taskTitle = `E2E Task ${id}`;
  await login(page, 'owner@agencyos.dev');
  await expect(page.getByRole('heading', { name: 'Operations', level: 1 })).toBeVisible();
  await page.getByRole('link', { name: 'Clients', exact: true }).click();
  await page.getByRole('button', { name: 'New client' }).click();
  const clientDialog = page.getByRole('dialog');
  await clientDialog.getByPlaceholder('Acme Robotics').fill(clientName);
  await clientDialog.getByRole('button', { name: 'Create client' }).click();
  await expect(page.getByRole('link', { name: clientName })).toBeVisible({ timeout: 15000 });
  await page.getByRole('link', { name: 'Projects', exact: true }).click();
  await page.getByRole('button', { name: 'New project' }).click();
  const projectDialog = page.getByRole('dialog');
  await projectDialog.getByRole('textbox').first().fill(projectName);
  await projectDialog.getByRole('combobox').first().click();
  await page.getByRole('option', { name: clientName }).click();
  await projectDialog.getByRole('button', { name: 'Create project' }).click();
  await expect(page.getByRole('link', { name: projectName })).toBeVisible({ timeout: 15000 });
  await page.getByRole('link', { name: projectName }).click();
  await expect(page.getByRole('heading', { name: projectName })).toBeVisible();
  await page.getByRole('button', { name: 'Add task' }).click();
  const taskDialog = page.getByRole('dialog');
  await taskDialog.getByRole('textbox').first().fill(taskTitle);
  await taskDialog.getByRole('button', { name: 'Create task' }).click();
  await expect(page.getByRole('button', { name: taskTitle, exact: true })).toBeVisible({ timeout: 15000 });
  await page.getByRole('button', { name: taskTitle, exact: true }).click();
  const editDialog = page.getByRole('dialog');
  await editDialog.getByRole('combobox').first().click();
  await page.getByRole('option', { name: 'IN PROGRESS' }).click();
  await editDialog.getByRole('button', { name: 'Save changes' }).click();
  await expect(editDialog).toBeHidden();
  const inProgressColumn = page.locator('div').filter({ hasText: /^In progress/ }).first();
  await expect(page.getByRole('button', { name: taskTitle, exact: true })).toBeVisible();
  await page.getByRole('button', { name: taskTitle, exact: true }).click();
  await expect(page.getByRole('dialog').getByRole('combobox').first()).toContainText('IN PROGRESS');
});
